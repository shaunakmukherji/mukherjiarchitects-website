// Web-sized copies of every project image (renders, gallery, construction photos) and the home hero.
//
// The originals in public/images/projects are only read, never changed. The copies are WebP files at
// several widths plus a 1200×630 JPEG share image per project, written to public/images/web/<project>/
// (git-ignored, rebuilt by every build) with a content hash in the name so they can be cached forever.
// Pages use the copies through generated/web-images.ts and fall back to the original if one is missing.
const fs = require('fs');
const path = require('path');
const { processImagesSync } = require('./web-images.cjs');

const PUBLIC_DIR = path.join(__dirname, '..', 'public');
const WEB_DIR = path.join(PUBLIC_DIR, 'images', 'web');
const IMAGE_EXT = /\.(jpe?g|png|webp)$/i;

const fileFor = (url) => path.join(PUBLIC_DIR, decodeURIComponent(url.split('?')[0]));
const nameFor = (url) =>
  path.basename(decodeURIComponent(url), path.extname(url)).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'image';

/**
 * @param projects  generated project list
 * @param heroUrl   the home page hero image (site path)
 * @returns { map: Record<sitePath, { w, h, variants, og? }>, ts: string }
 */
function buildProjectImages(projects, heroUrl) {
  const jobs = [];
  const add = (id, slug, url, extras) => {
    if (!url || !IMAGE_EXT.test(url) || !fs.existsSync(fileFor(url))) return;
    const used = new Set(jobs.filter((j) => j.slug === slug).map((j) => j.name));
    let name = nameFor(url);
    for (let n = 2; used.has(name); n++) name = `${nameFor(url)}-${n}`;
    jobs.push({ id, group: 'web', slug, file: fileFor(url), name, ...(extras ? { extras } : {}) });
  };

  for (const p of projects) {
    add(p.imageUrl, p.id, p.imageUrl, ['og']);
    for (const g of p.gallery ?? []) add(g, p.id, g);
    for (const m of p.constructionMedia ?? []) if (m.type === 'image') add(m.url, p.id, m.url);
  }
  if (heroUrl) add(heroUrl, 'hero', heroUrl);

  // Same image referenced twice (e.g. a project listed under two categories) → one job
  const unique = [...new Map(jobs.map((j) => [j.id, j])).values()];
  const results = processImagesSync(unique);

  const map = {};
  for (const job of unique) {
    const r = results[job.id];
    if (!r || !r.variants?.length) continue;
    const largest = r.variants[r.variants.length - 1];
    map[decodeURIComponent(job.id)] = { w: largest.w, h: largest.h, variants: r.variants, ...(r.og ? { og: r.og.url } : {}) };
  }

  // Remove copies of images that were replaced or deleted (only inside public/images/web, which is generated)
  const keep = new Set(Object.values(map).flatMap((m) => [...m.variants.map((v) => v.url), ...(m.og ? [m.og] : [])]));
  if (fs.existsSync(WEB_DIR)) {
    for (const slug of fs.readdirSync(WEB_DIR)) {
      const dir = path.join(WEB_DIR, slug);
      if (!fs.statSync(dir).isDirectory()) continue;
      for (const f of fs.readdirSync(dir)) {
        if (!keep.has(`/images/web/${slug}/${f}`)) fs.unlinkSync(path.join(dir, f));
      }
      if (!fs.readdirSync(dir).length) fs.rmdirSync(dir);
    }
  }

  const ts = `// Auto-generated by scripts/project-images.cjs — web-sized copies of project and hero images.
// Keys are the original image paths; the originals themselves are never modified.

export interface WebImageVariant { w: number; h: number; url: string }
export interface WebImage { w: number; h: number; variants: WebImageVariant[]; og?: string }

export const WEB_IMAGES: Record<string, WebImage> = ${JSON.stringify(map)};
`;
  return { map, ts, count: Object.keys(map).length };
}

module.exports = { buildProjectImages };
